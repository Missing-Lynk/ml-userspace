#define AIR_ADC_IIO_NAME   "artosyn-adc"    /* IIO name of the SAR ADC provider (artosyn_adc.ko) */
#define AIR_TEMP_IIO_NAME  "temperature"    /* IIO name of the SoC temp sensor (artosyn_protemp.ko) */
#define AIR_BATT_CHANNEL   1                /* SAR ADC channel wired to the battery sense */

/* Battery divider on our IIO driver's calibrated pin scale: metered 4.24 V pack / 888 mV
 * in_voltage1_input (bench, P1_SKY). battery_mV = in_voltage1_input * this. */
#define AIR_BATT_DIVIDER   4.775f

#define AIR_STATUS_B_IVL_MS 160            /* 0x11 periodic (~6 Hz) */
#define AIR_STATUS_A_IVL_MS 1000           /* 0x09 version/info (~1 Hz) */

#define AIR_HW_VERSION_DEFAULT "V1.0"      /* used when --hw-version is absent */

/* Datagrams serviced per socket per tick. A peer that floods must not be able to hold the loop:
 * the cap is far above the real rates (the goggle's :10000 requests are sub-Hz). */
#define AIR_RX_BURST_MAX   32

#define AIR_IDR_MIN_GAP_MS 500             /* floor between forced keyframes */

/* Keyframe-on-request state. */
struct air_idr {
    long last_ms;           /* when we last forced one, 0 = never */
    int warned_ctrl;
};

/* The consumers a bb reply can be routed to, bundled for the drain callback. */
struct air_bb_consumers {
    struct air_rate *rate;
    struct air_bind *bind;
    long now;
};

/* Destination for one MSP canvas frame. */
struct air_canvas_tx {
    int sock;
    struct sockaddr_in *dst;
    int *bound;
};

static char g_air_batt_path[160];          /* .../in_voltageN_input (calibrated pin mV) */
static char g_air_temp_path[160];          /* .../in_temp_scale (whole degC) */

/* Read a single integer from a sysfs file. Returns the value, or dflt on any error. */
static int air_read_int(const char *path, int dflt)
{
    char buf[32];
    int fd;
    ssize_t n;

    if (path[0] == '\0') {
        return dflt;
    }

    fd = open(path, O_RDONLY);
    if (fd < 0) {
        return dflt;
    }

    n = read(fd, buf, sizeof buf - 1);
    close(fd);
    if (n <= 0) {
        return dflt;
    }

    buf[n] = '\0';
    return (int)strtol(buf, NULL, 10);
}

/* Find the IIO device directory whose name attribute equals want, writing its path into dir.
 * Returns 0 on a match, -1 otherwise. IIO device indices are not stable, so resolve by name. */
static int air_iio_find(const char *want, char *dir, size_t dirsz)
{
    DIR *d = opendir("/sys/bus/iio/devices");
    struct dirent *e;
    int found = -1;

    if (d == NULL) {
        return -1;
    }

    while ((e = readdir(d)) != NULL) {
        char namepath[192];
        char name[64];
        int fd;
        ssize_t n;

        if (strncmp(e->d_name, "iio:device", 10) != 0) {
            continue;
        }

        snprintf(namepath, sizeof namepath, "/sys/bus/iio/devices/%s/name", e->d_name);
        fd = open(namepath, O_RDONLY);
        if (fd < 0) {
            continue;
        }

        n = read(fd, name, sizeof name - 1);
        close(fd);
        if (n <= 0) {
            continue;
        }

        name[n] = '\0';
        while (n > 0 && (name[n - 1] == '\n' || name[n - 1] == ' ')) {
            name[--n] = '\0';
        }

        if (strcmp(name, want) == 0) {
            snprintf(dir, dirsz, "/sys/bus/iio/devices/%s", e->d_name);
            found = 0;
            break;
        }
    }

    closedir(d);
    return found;
}

/* Resolve the battery ADC channel and the temperature sensor to concrete sysfs read paths. Returns
 * 0 when both are found. Retried by air_main until the IIO providers have coldplugged. */
static int air_iio_init(void)
{
    char adc_dir[160];
    char temp_dir[160];

    g_air_batt_path[0] = '\0';
    g_air_temp_path[0] = '\0';

    if (air_iio_find(AIR_ADC_IIO_NAME, adc_dir, sizeof adc_dir) == 0) {
        snprintf(g_air_batt_path, sizeof g_air_batt_path, "%s/in_voltage%d_input",
                 adc_dir, AIR_BATT_CHANNEL);
    }

    if (air_iio_find(AIR_TEMP_IIO_NAME, temp_dir, sizeof temp_dir) == 0) {
        snprintf(g_air_temp_path, sizeof g_air_temp_path, "%s/in_temp_scale", temp_dir);
    }

    return (g_air_batt_path[0] != '\0' && g_air_temp_path[0] != '\0') ? 0 : -1;
}

/* Battery voltage in millivolts from the board ADC: the calibrated pin mV times the divider
 * (-1 sentinel until the ADC path resolves). */
static int air_adc_voltage_mv(void)
{
    int pin_mv = air_read_int(g_air_batt_path, -1);

    if (pin_mv < 0) {
        return -1;
    }

    return (int)lroundf((float)pin_mv * AIR_BATT_DIVIDER);
}

/* FC voltage wins while fresh, matching the vendor's >0x708 mV precedence rule. The ADC is read
 * every time so verbose logs can show both values on bench. */
static int air_voltage_mv(const struct ml_msp *msp, long now, int *adc_mv, int *fc_mv)
{
    *adc_mv = air_adc_voltage_mv();
    *fc_mv = ml_msp_fc_voltage_mv(msp, now);

    if (*fc_mv >= 0) {
        return *fc_mv;
    }

    return *adc_mv;
}

/* SoC junction temperature in whole degrees C (in_temp_scale carries the whole value directly). */
static int air_temp_c(void)
{
    return air_read_int(g_air_temp_path, 0);
}

/* Bind a UDP socket to the air unit's local address (10.0.0.100) on port. */
static int air_bind_local(int sock, int port)
{
    struct sockaddr_in local;

    memset(&local, 0, sizeof local);
    local.sin_family = AF_INET;
    inet_pton(AF_INET, AIR_ADDR, &local.sin_addr);
    local.sin_port = htons(port);

    return bind(sock, (struct sockaddr *)&local, sizeof local);
}

/* MEDIA_IDR_REQUEST: force a keyframe on demand.
 *
 * The stream carries one IDR at FrameId 0 and P-frames after, vendor-exact, so a receiver that was
 * not listening at session start needs a fresh one to decode at all. This request is the vendor's
 * repair path: AR_FSM_TX_ProcessIdrRequest @0x428938 calls AR_LDRT_TX_PIPELINE_IdrEnable while
 * already streaming. ml-air-video's keyframe command is the same thing, and it re-sends VPS/SPS/PPS
 * with the IDR so a late joiner gets parameter sets too.
 *
 * Requests are decoder-driven and therefore rare. Honouring at most one per AIR_IDR_MIN_GAP_MS
 * bounds what a receiver that keeps asking can cost, and sits well under the goggle's 2 s request
 * cadence, so a real request is never suppressed. */

static void air_idr_request(struct air_idr *idr, long now)
{
    if (idr->last_ms != 0 && now - idr->last_ms < AIR_IDR_MIN_GAP_MS) {
        return;
    }

    if (air_ctrl_send("keyframe\n") != 0) {
        if (!idr->warned_ctrl) {
            fprintf(stderr, TAG " idr: ml-air-video control socket not answering, retrying\n");
            idr->warned_ctrl = 1;
        }

        return;
    }

    idr->warned_ctrl = 0;
    idr->last_ms = now;

    if (g_verbose) {
        fprintf(stderr, TAG " idr: keyframe forced on request\n");
    }
}

/* Route one bb reply to whichever consumer owns that selector. Anything else, the ch05 chip log
 * included, is read and dropped so the socket cannot back up. */
static void air_bb_reply(uint8_t selector, const uint8_t *payload, int plen, void *ctx)
{
    struct air_bb_consumers *consumers = ctx;

    if (selector == GET_MCS) {
        air_rate_reply(consumers->rate, payload, plen, consumers->now);
    } else if (selector == GET_PAIR) {
        air_bind_pair_reply(consumers->bind, payload, plen);
    }
}

/* The air role loop: transmit :10000 status telemetry to the goggle and answer its :20001 probe.
 * Sockets are (re)bound and the IIO providers (re)resolved each tick until sdio0 and the modules
 * are up, so it is safe to start before ml-rf-bringup has finished. */
static void air_send_canvas(const uint8_t *canvas, size_t len, void *ctx)
{
    struct air_canvas_tx *tx = ctx;
    struct timespec t;
    uint8_t frame[PKT_MAX];
    uint32_t stamp_us;

    if (tx->bound == NULL || !*tx->bound ||
        len > UINT8_MAX || MP_OFF_BODY + len + MP_TRAILER_LEN > sizeof frame) {
        return;
    }

    clock_gettime(CLOCK_MONOTONIC, &t);
    stamp_us = (uint32_t)(t.tv_sec * 1000000ULL + t.tv_nsec / 1000);
    sendto(tx->sock, frame, mp_msp_canvas(frame, canvas, (uint8_t)len, stamp_us), MSG_DONTWAIT,
           (struct sockaddr *)tx->dst, sizeof *tx->dst);
}

void air_main(const char *hw_version, const char *fc_tty, enum ml_rate_mode rate_mode)
{
    struct air_bb bb = { .fd = -1 };
    struct air_rate rate = { .mode = rate_mode, .mcs = -1, .pending_mcs = -1 };
    struct air_idr idr = { 0 };
    struct air_bind button = { .fd = -1, .green_saved = -1 };
    int status_sock = socket(AF_INET, SOCK_DGRAM, 0);
    int hello_sock = socket(AF_INET, SOCK_DGRAM, 0);
    struct sockaddr_in goggle_status, goggle_hello;
    int status_bound = 0, hello_bound = 0, iio_ok = 0, warned_iio = 0;
    struct air_canvas_tx canvas_tx = { .sock = status_sock, .dst = &goggle_status,
                                       .bound = &status_bound };
    struct ml_msp msp;
    long last_a = 0, last_b = 0;
    int msp_warned = 0;
    int one = 1;

    if (hw_version == NULL || hw_version[0] == '\0') {
        hw_version = AIR_HW_VERSION_DEFAULT;
    }

    if (fc_tty == NULL || fc_tty[0] == '\0') {
        fc_tty = ML_MSP_DEFAULT_TTY;
    }

    ml_msp_init(&msp, air_send_canvas, &canvas_tx);

    setsockopt(status_sock, SOL_SOCKET, SO_REUSEADDR, &one, sizeof one);
    setsockopt(hello_sock, SOL_SOCKET, SO_REUSEADDR, &one, sizeof one);

    memset(&goggle_status, 0, sizeof goggle_status);
    goggle_status.sin_family = AF_INET;
    inet_pton(AF_INET, LOCAL_ADDR, &goggle_status.sin_addr);
    goggle_hello = goggle_status;
    goggle_status.sin_port = htons(PARAMS_PORT);
    goggle_hello.sin_port = htons(HELLO_PORT);

    printf(TAG " role=air: telemetry TX to %s:%d, FC MSP on %s\n",
           LOCAL_ADDR, PARAMS_PORT, fc_tty);
    fflush(stdout);

    while (g_run) {
        long now = now_ms();
        struct timespec t;
        uint32_t stamp_us;
        uint8_t frame[MP_STATUS_A_TOTAL];
        uint8_t rx[HELLO_LEN];
        uint8_t mp_rx[PKT_MAX];
        ssize_t n;

        if (!status_bound && air_bind_local(status_sock, PARAMS_PORT) == 0) {
            status_bound = 1;
        }

        if (!hello_bound && air_bind_local(hello_sock, HELLO_PORT) == 0) {
            hello_bound = 1;
        }

        if (!iio_ok) {
            iio_ok = (air_iio_init() == 0);
            if (!iio_ok && !warned_iio) {
                fprintf(stderr, TAG " IIO not ready (artosyn_adc/protemp not loaded?), retrying\n");
                warned_iio = 1;
            }
        }

        if (msp.fd < 0 && ml_msp_open(&msp, fc_tty) != 0) {
            if (!msp_warned) {
                fprintf(stderr, TAG " FC MSP UART %s not ready, retrying\n", fc_tty);
                msp_warned = 1;
            }
        }

        clock_gettime(CLOCK_MONOTONIC, &t);
        stamp_us = (uint32_t)(t.tv_sec * 1000000ULL + t.tv_nsec / 1000);
        ml_msp_service(&msp, now);
        air_rate_service(&rate, &bb, now);
        air_bind_service(&button, &bb, now);
        air_bind_pair_service(&button, &bb, now);
        struct air_bb_consumers consumers = { .rate = &rate, .bind = &button, .now = now };

        air_bb_drain(&bb, air_bb_reply, &consumers);

        /* 0x11 periodic (~6 Hz): FC status fields plus voltage with ADC fallback. */
        if (status_bound && now - last_b >= AIR_STATUS_B_IVL_MS) {
            int adc_mv;
            int fc_mv;
            int mv = air_voltage_mv(&msp, now, &adc_mv, &fc_mv);

            if (mv >= 0) {
                sendto(status_sock, frame,
                       mp_status_periodic(frame, msp.status.arm_flag, msp.status.mah_drawn_x10,
                                          (uint16_t)mv, stamp_us),
                       MSG_DONTWAIT, (struct sockaddr *)&goggle_status, sizeof goggle_status);
            }

            last_b = now;
        }

        /* 0x09 version/info (~1 Hz): hw/fw strings, voltage, air temperature. */
        if (status_bound && now - last_a >= AIR_STATUS_A_IVL_MS) {
            int adc_mv;
            int fc_mv;
            int mv = air_voltage_mv(&msp, now, &adc_mv, &fc_mv);
            int tc = air_temp_c();

            sendto(status_sock, frame,
                   mp_status_version(frame, hw_version, ML_VERSION,
                                     (uint16_t)(mv >= 0 ? mv : 0), (uint16_t)tc, stamp_us),
                   MSG_DONTWAIT, (struct sockaddr *)&goggle_status, sizeof goggle_status);

            if (g_verbose) {
                fprintf(stderr, TAG " tx status voltage=%d mV adc=%d mV fc=%d mV arm=%u mah_x10=%u temp=%d C\n",
                        mv, adc_mv, fc_mv, msp.status.arm_flag, msp.status.mah_drawn_x10, tc);
            }

            last_a = now;
        }

        /* Answer the goggle's :20001 identity probe: echo the 520-byte type-0 datagram back verbatim
         * with byte[0]=0x01 (the type-1 identity); the goggle replies with the byte[0]=0x02 ACK. */
        for (int got = 0; hello_bound && got < AIR_RX_BURST_MAX &&
             (n = recvfrom(hello_sock, rx, sizeof rx, MSG_DONTWAIT, NULL, NULL)) > 0; got++) {
            if (rx[0] == 0x00) {
                rx[0] = 0x01;
                sendto(hello_sock, rx, n, MSG_DONTWAIT,
                       (struct sockaddr *)&goggle_hello, sizeof goggle_hello);
            }
        }

        /* Service the goggle's :10000 datagrams. Everything is drained every tick either way, so the
         * receive buffer stays clear; the two types below are answered. */
        for (int got = 0; status_bound && got < AIR_RX_BURST_MAX &&
             (n = recvfrom(status_sock, mp_rx, sizeof mp_rx, MSG_DONTWAIT, NULL, NULL)) > 0; got++) {
            uint32_t msg_type;

            if ((size_t)n < 4) {
                continue;
            }

            memcpy(&msg_type, mp_rx, 4);

            if (msg_type == MP_REQUEST) {
                /* The goggle gates its whole session on this reply: it drives the IDR request, the
                 * solid-green LED and the video-stall watch (ml-linkd.c g_params_acked). Answering
                 * changes no air-side state, matching AR_FSM_TX_ProcessParamsRequest @0x4284e8. */
                sendto(status_sock, frame, mp_params_reply(frame, stamp_us), MSG_DONTWAIT,
                       (struct sockaddr *)&goggle_status, sizeof goggle_status);

                if (g_verbose) {
                    fprintf(stderr, TAG " rx MEDIA_PARAMS_REQUEST -> reply\n");
                }
            } else if (msg_type == MP_IDR_REQUEST) {
                air_idr_request(&idr, now);
            } else if (g_verbose) {
                fprintf(stderr, TAG " rx :10000 type 0x%02x (%zd B), ignored\n",
                        msg_type, (ssize_t)n);
            }
        }

        usleep(air_bind_active(&button) ? AIR_BIND_TICK_US : UDP_TICK_US);
    }

    close(status_sock);
    close(hello_sock);
    ml_msp_close(&msp);

    if (air_bind_active(&button)) {
        air_bind_abort(&button, &bb, "shutdown");
    }

    if (button.fd >= 0) {
        close(button.fd);
    }

    if (bb.fd >= 0) {
        close(bb.fd);
    }

    printf(TAG " role=air clean stop\n");
}
